CREATE TABLE IF NOT EXISTS dorm_stay (
  id BIGINT NOT NULL AUTO_INCREMENT,
  student_id BIGINT NOT NULL,
  student_no VARCHAR(64) NOT NULL,
  student_name VARCHAR(100) NOT NULL,
  class_id BIGINT NOT NULL,
  class_name VARCHAR(100) NOT NULL,
  gender VARCHAR(16) NOT NULL,
  bed_id BIGINT NOT NULL,
  room_id BIGINT NOT NULL,
  building_id BIGINT NOT NULL,
  bed_label VARCHAR(255) NOT NULL,
  status VARCHAR(20) NOT NULL,
  check_in_time DATETIME(6) NULL,
  check_out_time DATETIME(6) NULL,
  deposit_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
  deduction_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
  refund_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
  inspection VARCHAR(1000) NULL,
  deduction_reason VARCHAR(500) NULL,
  refund_status VARCHAR(20) NOT NULL,
  refund_time DATETIME(6) NULL,
  refund_account_id BIGINT NULL,
  row_version BIGINT NOT NULL DEFAULT 1,
  tenant_id BIGINT NOT NULL,
  creator VARCHAR(64) NOT NULL DEFAULT '',
  create_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updater VARCHAR(64) NOT NULL DEFAULT '',
  update_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  deleted BIT(1) NOT NULL DEFAULT b'0',
  PRIMARY KEY (id),
  active_student_id BIGINT GENERATED ALWAYS AS (CASE WHEN deleted = b'0' AND status IN ('RESERVED','OCCUPIED') THEN student_id ELSE NULL END) STORED,
  active_bed_id BIGINT GENERATED ALWAYS AS (CASE WHEN deleted = b'0' AND status IN ('RESERVED','OCCUPIED') THEN bed_id ELSE NULL END) STORED,
  UNIQUE KEY uk_dorm_stay_student (tenant_id, active_student_id),
  UNIQUE KEY uk_dorm_stay_bed (tenant_id, active_bed_id),
  KEY idx_dorm_stay_scope (tenant_id, class_id, status, deleted),
  KEY idx_dorm_stay_room (tenant_id, room_id, status, deleted),
  KEY idx_dorm_stay_building (tenant_id, building_id, status, deleted),
  KEY idx_dorm_stay_student (tenant_id, student_id, deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

