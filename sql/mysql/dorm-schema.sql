CREATE TABLE IF NOT EXISTS dorm_trip (
  id BIGINT NOT NULL AUTO_INCREMENT,
  student_id BIGINT NOT NULL,
  student_no VARCHAR(64) NOT NULL,
  student_name VARCHAR(100) NOT NULL,
  class_id BIGINT NOT NULL,
  class_name VARCHAR(100) NOT NULL,
  depart_request_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  depart_fingerprint CHAR(64) NOT NULL,
  return_request_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  return_fingerprint CHAR(64) NULL,
  depart_time DATETIME(6) NOT NULL,
  depart_latitude DECIMAL(10,7) NOT NULL,
  depart_longitude DECIMAL(10,7) NOT NULL,
  depart_accuracy DECIMAL(10,2) NOT NULL,
  depart_captured_at DATETIME(6) NOT NULL,
  return_time DATETIME(6) NULL,
  return_latitude DECIMAL(10,7) NULL,
  return_longitude DECIMAL(10,7) NULL,
  return_accuracy DECIMAL(10,2) NULL,
  return_captured_at DATETIME(6) NULL,
  review_status VARCHAR(20) NOT NULL,
  reviewer_id BIGINT NULL,
  reviewed_at DATETIME(6) NULL,
  review_reason VARCHAR(500) NULL,
  photo_id BIGINT NULL,
  row_version BIGINT NOT NULL DEFAULT 1,
  tenant_id BIGINT NOT NULL,
  creator VARCHAR(64) NOT NULL DEFAULT '',
  create_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updater VARCHAR(64) NOT NULL DEFAULT '',
  update_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  deleted BIT(1) NOT NULL DEFAULT b'0',
  PRIMARY KEY (id),
  active_student_id BIGINT GENERATED ALWAYS AS (CASE WHEN deleted=b'0' AND return_time IS NULL THEN student_id ELSE NULL END) STORED,
  UNIQUE KEY uk_dorm_trip_active (tenant_id, active_student_id),
  UNIQUE KEY uk_dorm_depart_request (tenant_id, student_id, depart_request_id),
  UNIQUE KEY uk_dorm_return_request (tenant_id, student_id, return_request_id),
  KEY idx_dorm_trip_scope (tenant_id, class_id, depart_time, deleted),
  KEY idx_dorm_trip_student (tenant_id, student_id, depart_time, deleted)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

